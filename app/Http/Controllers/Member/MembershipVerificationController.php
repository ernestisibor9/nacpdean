<?php

namespace App\Http\Controllers\Member;

use App\Http\Controllers\Controller;
use App\Models\MembershipCard;
use Carbon\Carbon;

class MembershipVerificationController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | VERIFY MEMBERSHIP CARD
    |--------------------------------------------------------------------------
    */

    public function verify($qrToken)
    {
        /*
        |--------------------------------------------------------------------------
        | FIND CARD
        |--------------------------------------------------------------------------
        */

        $card = MembershipCard::with([
            'membership',
            'profile',
            'category',
        ])
            ->where('qr_token', trim($qrToken))
            ->first();

        /*
        |--------------------------------------------------------------------------
        | INVALID QR CODE
        |--------------------------------------------------------------------------
        */

        if (!$card) {
            return view('verification.membership', [
                'card' => null,
                'valid' => false,
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | CARD STATUS
        |--------------------------------------------------------------------------
        */

        $valid = true;

        if ($card->status !== 'active') {
            $valid = false;
        }

        /*
        |--------------------------------------------------------------------------
        | CARD EXPIRY
        |--------------------------------------------------------------------------
        */

        if (
            $card->expires_at &&
            Carbon::parse($card->expires_at)->lt(today())
        ) {
            $valid = false;
        }

        /*
        |--------------------------------------------------------------------------
        | MEMBERSHIP STATUS
        |--------------------------------------------------------------------------
        */

        if (
            !$card->membership ||
            $card->membership->status !== 'active'
        ) {
            $valid = false;
        }

        /*
        |--------------------------------------------------------------------------
        | PROFILE
        |--------------------------------------------------------------------------
        */

        if (!$card->profile) {
            $valid = false;
        }

        /*
        |--------------------------------------------------------------------------
        | CATEGORY
        |--------------------------------------------------------------------------
        */

        if (!$card->category) {
            $valid = false;
        }

        /*
        |--------------------------------------------------------------------------
        | VERIFICATION VIEW
        |--------------------------------------------------------------------------
        */

        return view('verification.membership', [
            'card' => $card,
            'valid' => $valid,
        ]);
    }
}
